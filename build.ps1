# Concatenates src/*.sql, in file-name order, into the single install script aisqltuner-index-tuner.sql.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$out = Join-Path $root 'aisqltuner-index-tuner.sql'

$header = @"
/*
    aisqltuner-index-tuner: AI-assisted index tuning from inside SQL Server.
    Free and open source from AI SQL Tuner (https://aisqltuner.com).
    For query tuning, deadlock analysis, server health checks, code review, HTML reports or
    SQL Server 2022 and earlier, see AI SQL Tuner Studio: https://aisqltuner.com or the
    Microsoft Store, https://apps.microsoft.com/detail/9P68072ZM3N5

    Install: run this script in the user database you want to tune, then run
    setup/Configure-Endpoint.sql. Requires SQL Server 2025, Azure SQL Database,
    Azure SQL Managed Instance or Fabric SQL Database.

    Generated by build.ps1 from src/. Edit the files in src/, not this one.
*/

"@

$parts = Get-ChildItem (Join-Path $root 'src') -Filter '*.sql' | Sort-Object Name | ForEach-Object {
    "/* ===== $($_.Name) ===== */`r`n" + (Get-Content $_.FullName -Raw -Encoding UTF8)
}

[IO.File]::WriteAllText($out, $header + ($parts -join "`r`n"), (New-Object Text.UTF8Encoding $true))
Write-Host "Wrote $out"
